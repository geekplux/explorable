// node scripts/gen-sw.mjs [dir]: post-build step (docs/PLAN.md §5.7, O2). Writes
// <dir>/sw.js (default dist/client) that precaches the app shell, every asset and
// the fonts under a cache name hashed from the build, so a new deploy gets a new
// cache. Matching ignores Vary (static files; vite preview adds Vary: Origin).
// Navigations are network-first with the cached shell as the offline
// fallback; files are cache-first. `/api/*`, the sample PDFs (`/pdf/*`, downloaded on demand, never precached)
// and other origins are never touched.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const SW = 'sw.js';
/** Not precached: the shell is cached as `/` (Static Assets redirects /index.html), platform files, and the social cards (read by link previews, not the app). */
const SKIP = new Set(['index.html', SW, '_headers', '_redirects', '.assetsignore', 'social-preview.png', 'og.jpg', 'og.mp4']);
const SKIP_EXT = /\.(?:map|txt|pdf)$/;

/** Every file under `dir`, as sorted posix paths relative to it. @returns {string[]} */
export function listFiles(dir, prefix = '') {
  return readdirSync(join(dir, prefix), { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? listFiles(dir, `${prefix}${e.name}/`) : [`${prefix}${e.name}`]))
    .toSorted();
}

/** The URLs to precache: the shell `/` first, then every shippable file. */
export const precacheUrls = (files) => ['/', ...files.filter((f) => !SKIP.has(f) && !SKIP_EXT.test(f)).map((f) => `/${f}`)];

/** `explorable-<12 hex>` from every file's path and bytes (sw.js itself excluded). */
export function cacheName(dir, files) {
  const hash = createHash('sha256');
  for (const f of files.filter((name) => name !== SW)) hash.update(`${f}\0`).update(readFileSync(join(dir, f)));
  return `explorable-${hash.digest('hex').slice(0, 12)}`;
}

/** The service worker source for a cache name and precache list. */
export const serviceWorker = (name, urls) => `// Generated by scripts/gen-sw.mjs; do not edit.
const CACHE = ${JSON.stringify(name)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('explorable-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.skipWaiting())
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || ['/api/', '/pdf/'].some((p) => url.pathname.startsWith(p))) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/', { cacheName: CACHE, ignoreVary: true }).then((shell) => shell || Response.error())));
    return;
  }
  event.respondWith(caches.match(request, { cacheName: CACHE, ignoreVary: true }).then((hit) => hit || fetch(request)));
});
`;

/** Write `<dir>/sw.js`; returns { name, urls }. */
export function generate(dir = 'dist/client') {
  if (!existsSync(join(dir, 'index.html'))) throw new Error(`${dir}/index.html not found: build first`);
  const files = listFiles(dir);
  const name = cacheName(dir, files);
  const urls = precacheUrls(files);
  writeFileSync(join(dir, SW), serviceWorker(name, urls));
  return { name, urls };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const { name, urls } = generate(process.argv[2]);
  console.log(`sw.js: ${name}, ${urls.length} precached URLs`);
}
